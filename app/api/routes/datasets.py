def _get_dataset_with_analysis(
    dataset_id: str,
    db: Session,
) -> Dataset:
    dataset = db.scalar(
        select(Dataset)
        .options(
            joinedload(
                Dataset.analysis,
            )
        )
        .where(
            Dataset.id == dataset_id,
        )
    )

    if (
        dataset is None
        or dataset.analysis is None
    ):
        raise HTTPException(
            status_code=404,
            detail=(
                "Dataset analysis not found."
            ),
        )

    return dataset


def _load_dataset_profile(
    dataset: Dataset,
) -> DatasetProfile:
    if dataset.analysis is None:
        raise HTTPException(
            status_code=404,
            detail=(
                "Dataset analysis not found."
            ),
        )

    try:
        return DatasetProfile.model_validate(
            dataset.analysis.profile_json,
        )
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=(
                "The stored dataset profile "
                "could not be loaded."
            ),
        ) from exc


def _safe_filename_stem(
    filename: str,
) -> str:
    stem = Path(
        filename,
    ).stem.strip()

    if not stem:
        stem = "dataset"

    safe_stem = "".join(
        character
        if (
            character.isalnum()
            or character
            in {
                "-",
                "_",
            }
        )
        else "_"
        for character in stem
    )

    return safe_stem


def _build_report_filename(
    filename: str,
) -> str:
    return (
        f"{_safe_filename_stem(filename)}"
        "_report.pdf"
    )


def _build_script_filename(
    filename: str,
    script_format: str,
) -> str:
    extension_by_format = {
        "pandas": "py",
        "pyspark": "py",
        "sql": "sql",
    }

    extension = (
        extension_by_format[
            script_format
        ]
    )

    return (
        f"{_safe_filename_stem(filename)}"
        f"_cleaning_{script_format}."
        f"{extension}"
    )


def _build_cleaning_script(
    profile: DatasetProfile,
    script_format: Literal[
        "pandas",
        "pyspark",
        "sql",
    ],
) -> str:
    plan = build_cleaning_plan(
        profile,
    )

    actions = plan.get(
        "actions",
        [],
    )

    if script_format == "pandas":
        header = (
            '"""Generated by SignalForge AI.\n\n'
            "Review all transformations before applying "
            "them to production data.\n"
            '"""\n\n'
            "import pandas as pd\n\n"
            "# Load the source dataset.\n"
            f'df = pd.read_csv("{profile.filename}")\n'
        )

        footer = (
            "\n\n# Save the cleaned dataset.\n"
            'df.to_csv("cleaned_dataset.csv", index=False)\n'
        )

        code_key = "pandas_code"

    elif script_format == "pyspark":
        header = (
            '"""Generated by SignalForge AI.\n\n'
            "Review all transformations before applying "
            "them to production data.\n"
            '"""\n\n'
            "from pyspark.sql import SparkSession\n\n"
            "spark = (\n"
            "    SparkSession.builder\n"
            '    .appName("SignalForgeCleaning")\n'
            "    .getOrCreate()\n"
            ")\n\n"
            "# Load the source dataset.\n"
            "df = (\n"
            "    spark.read\n"
            '    .option("header", True)\n'
            '    .option("inferSchema", True)\n'
            f'    .csv("{profile.filename}")\n'
            ")\n"
        )

        footer = (
            "\n\n# Save the cleaned dataset.\n"
            "(\n"
            "    df.write\n"
            '    .mode("overwrite")\n'
            '    .option("header", True)\n'
            '    .csv("cleaned_dataset")\n'
            ")\n"
        )

        code_key = "pyspark_code"

    else:
        header = (
            "-- Generated by SignalForge AI.\n"
            "-- Review all transformations before "
            "applying them to production data.\n"
            "-- Replace source_table and destination_table "
            "with your actual table names.\n"
        )

        footer = (
            "\n\n-- Validate the cleaned output before "
            "replacing any production table.\n"
        )

        code_key = "sql_code"

    sections: list[str] = [
        header,
    ]

    if not actions:
        sections.append(
            (
                "\n# No automated cleaning actions "
                "were generated.\n"
            )
            if script_format
            != "sql"
            else (
                "\n-- No automated cleaning actions "
                "were generated.\n"
            )
        )
    else:
        for index, action in enumerate(
            actions,
            start=1,
        ):
            title = str(
                action.get(
                    "title",
                    "Cleaning action",
                )
            )

            reason = str(
                action.get(
                    "reason",
                    "",
                )
            )

            code = str(
                action.get(
                    code_key,
                    "",
                )
            ).strip()

            comment_prefix = (
                "#"
                if script_format
                in {
                    "pandas",
                    "pyspark",
                }
                else "--"
            )

            sections.append(
                (
                    f"\n\n{comment_prefix} "
                    f"Action {index}: {title}\n"
                    f"{comment_prefix} "
                    f"Reason: {reason}\n"
                    f"{code}\n"
                )
            )

    sections.append(
        footer,
    )

    return "".join(
        sections,
    )


@router.post(
    "/datasets/profile",
    response_model=DatasetProfileResponse,
)
async def profile_dataset(
    request: Request,
    file: UploadFile = File(...),
    db: Session = Depends(get_db),
) -> DatasetProfileResponse:
    settings = (
        request.app.state.settings
    )

    stored_dataset = (
        await store_uploaded_csv(
            file=file,
            settings=settings,
        )
    )

    processed = process_stored_dataset(
        stored_dataset=stored_dataset,
        settings=settings,
        db=db,
    )

    return DatasetProfileResponse(
        dataset_id=(
            processed.dataset.id
        ),
        created_at=(
            processed.dataset.uploaded_at
        ),
        parent_dataset_id=(
            processed.dataset
            .parent_dataset_id
        ),
        version_number=(
            processed.dataset
            .version_number
        ),
        version_type=(
            processed.dataset
            .version_type
        ),
        **processed.profile.model_dump(),
    )


@router.get(
    "/datasets",
    response_model=list[
        DatasetSummary
    ],
)
def list_datasets(
    db: Session = Depends(get_db),
) -> list[DatasetSummary]:
    datasets = db.scalars(
        select(Dataset)
        .options(
            joinedload(
                Dataset.analysis,
            )
        )
        .where(
            Dataset.analysis.has(),
        )
        .order_by(
            desc(
                Dataset.uploaded_at,
            )
        )
    ).all()

    summaries: list[
        DatasetSummary
    ] = []

    for dataset in datasets:
        analysis = (
            dataset.analysis
        )

        if analysis is None:
            continue

        summaries.append(
            DatasetSummary(
                id=dataset.id,
                filename=(
                    analysis.filename
                ),
                row_count=(
                    analysis.row_count
                ),
                column_count=(
                    analysis.column_count
                ),
                reliability_score=(
                    analysis
                    .reliability_score
                ),
                created_at=(
                    analysis.created_at
                ),
                parent_dataset_id=(
                    dataset
                    .parent_dataset_id
                ),
                version_number=(
                    dataset
                    .version_number
                ),
                version_type=(
                    dataset
                    .version_type
                ),
            )
        )

    return summaries


@router.post(
    "/datasets/{dataset_id}/copilot",
    response_model=CopilotResponse,
)
def ask_dataset_copilot(
    dataset_id: str,
    request_body: CopilotRequest,
    db: Session = Depends(get_db),
) -> CopilotResponse:
    dataset = (
        _get_dataset_with_analysis(
            dataset_id=dataset_id,
            db=db,
        )
    )

    profile = (
        _load_dataset_profile(
            dataset,
        )
    )

    try:
        return answer_copilot_question(
            dataset_id=dataset.id,
            profile=profile,
            question=(
                request_body.question
            ),
        )
    except ValueError as exc:
        raise HTTPException(
            status_code=400,
            detail=str(exc),
        ) from exc
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=(
                "The dataset copilot "
                "could not generate an answer."
            ),
        ) from exc


@router.get(
    "/datasets/{dataset_id}/report",
    response_class=Response,
    responses={
        200: {
            "content": {
                "application/pdf": {},
            },
            "description": (
                "Download the executive "
                "PDF report."
            ),
        },
        404: {
            "description": (
                "Dataset analysis not found."
            ),
        },
    },
)
def download_dataset_report(
    dataset_id: str,
    db: Session = Depends(get_db),
) -> Response:
    dataset = (
        _get_dataset_with_analysis(
            dataset_id=dataset_id,
            db=db,
        )
    )

    profile = (
        _load_dataset_profile(
            dataset,
        )
    )

    try:
        pdf_bytes = (
            build_dataset_pdf_report(
                profile=profile,
                dataset_id=dataset.id,
                created_at=(
                    dataset.uploaded_at
                ),
            )
        )
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=(
                "The PDF report could "
                "not be generated."
            ),
        ) from exc

    report_filename = (
        _build_report_filename(
            profile.filename,
        )
    )

    return Response(
        content=pdf_bytes,
        media_type=(
            "application/pdf"
        ),
        headers={
            "Content-Disposition": (
                f'attachment; filename="'
                f'{report_filename}"'
            ),
            "Cache-Control": (
                "no-store"
            ),
        },
    )


