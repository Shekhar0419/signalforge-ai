@router.get(
    "/datasets/{dataset_id}/cleaning-script",
    response_class=Response,
)
def download_dataset_cleaning_script(
    dataset_id: str,
    format: Literal[
        "pandas",
        "pyspark",
        "sql",
    ] = Query(
        default="pandas",
        description=(
            "Script format: pandas, "
            "pyspark, or sql."
        ),
    ),
    db: Session = Depends(get_db),
) -> Response:
    dataset = (
        _get_dataset_with_analysis(
            dataset_id=dataset_id,
            db=db,
        )
    )

    profile = (
        _load_dataset_profile(
            dataset,
        )
    )

    try:
        script = (
            _build_cleaning_script(
                profile=profile,
                script_format=format,
            )
        )
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=(
                "The cleaning script could "
                "not be generated."
            ),
        ) from exc

    filename = (
        _build_script_filename(
            filename=profile.filename,
            script_format=format,
        )
    )

    media_type_by_format = {
        "pandas": (
            "text/x-python; "
            "charset=utf-8"
        ),
        "pyspark": (
            "text/x-python; "
            "charset=utf-8"
        ),
        "sql": (
            "application/sql; "
            "charset=utf-8"
        ),
    }

    return Response(
        content=script.encode(
            "utf-8",
        ),
        media_type=(
            media_type_by_format[
                format
            ]
        ),
        headers={
            "Content-Disposition": (
                f'attachment; filename="'
                f'{filename}"'
            ),
            "Cache-Control": (
                "no-store"
            ),
        },
    )


